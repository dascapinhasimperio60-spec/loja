-- ---------------------------------------------------------------------------
-- Categorias
-- ---------------------------------------------------------------------------
create table if not exists public.categories (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  slug text not null unique,
  position integer not null default 0,
  created_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- Produtos
-- ---------------------------------------------------------------------------
create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  code integer generated by default as identity (start with 101) unique,
  slug text not null unique,
  title text not null check (char_length(title) between 2 and 140),
  description text not null default '',
  price numeric(10, 2) not null check (price >= 0),
  compare_at_price numeric(10, 2) check (compare_at_price is null or compare_at_price >= 0),
  ml_url text not null default '',
  category_id uuid references public.categories (id) on delete set null,
  models text[] not null default '{}',
  material text not null default '',
  includes text not null default '',
  featured boolean not null default false,
  active boolean not null default true,
  sold_out boolean not null default false,
  position integer not null default 0,
  click_count integer not null default 0,
  last_click_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists products_active_idx on public.products (active, position, created_at desc);
create index if not exists products_category_idx on public.products (category_id);
create index if not exists products_models_idx on public.products using gin (models);

-- ---------------------------------------------------------------------------
