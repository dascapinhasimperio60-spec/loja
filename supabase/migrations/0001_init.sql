alter table public.product_images enable row level security;
alter table public.click_daily enable row level security;

-- admins: cada admin enxerga a própria linha
drop policy if exists admins_self on public.admins;
create policy admins_self on public.admins
  for select to authenticated using (user_id = (select auth.uid()));

-- settings
drop policy if exists settings_read on public.settings;
create policy settings_read on public.settings
  for select to anon, authenticated using (true);
drop policy if exists settings_write on public.settings;
create policy settings_write on public.settings
  for update to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));

-- categories
drop policy if exists categories_read on public.categories;
create policy categories_read on public.categories
  for select to anon, authenticated using (true);
drop policy if exists categories_write on public.categories;
create policy categories_write on public.categories
  for all to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));

-- products
drop policy if exists products_read on public.products;
create policy products_read on public.products
  for select to anon, authenticated using (active or (select public.is_admin()));
drop policy if exists products_write on public.products;
create policy products_write on public.products
  for all to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));

-- product_images
drop policy if exists product_images_read on public.product_images;
create policy product_images_read on public.product_images
  for select to anon, authenticated using (
    exists (select 1 from public.products p where p.id = product_id and (p.active or (select public.is_admin())))
  );
drop policy if exists product_images_write on public.product_images;
create policy product_images_write on public.product_images
  for all to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));

-- click_daily: só admin lê; escrita só pela função register_click
drop policy if exists click_daily_read on public.click_daily;
create policy click_daily_read on public.click_daily
  for select to authenticated using ((select public.is_admin()));

