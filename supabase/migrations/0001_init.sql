create index if not exists product_images_product_idx on public.product_images (product_id, position);

-- ---------------------------------------------------------------------------
-- Cliques em "Comprar" agregados por dia (1 linha por produto/dia)
-- ---------------------------------------------------------------------------
create table if not exists public.click_daily (
  product_id uuid not null references public.products (id) on delete cascade,
  day date not null default (now() at time zone 'America/Sao_Paulo')::date,
  kind text not null default 'ml' check (kind in ('ml', 'whatsapp')),
  count integer not null default 0,
  primary key (product_id, day, kind)
);

create or replace function public.register_click(p_product_id uuid, p_kind text default 'ml')
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_kind text := case when p_kind = 'whatsapp' then 'whatsapp' else 'ml' end;
begin
  if not exists (select 1 from products where id = p_product_id and active) then
    return;
  end if;

  if v_kind = 'ml' then
    update products
      set click_count = click_count + 1, last_click_at = now()
      where id = p_product_id;
  end if;

  insert into click_daily (product_id, day, kind, count)
    values (p_product_id, (now() at time zone 'America/Sao_Paulo')::date, v_kind, 1)
    on conflict (product_id, day, kind) do update set count = click_daily.count + 1;
end;
$$;

revoke all on function public.register_click(uuid, text) from public;
grant execute on function public.register_click(uuid, text) to anon, authenticated;

-- Impede que o trigger de updated_at seja disparado por cliques
-- (assim "atualizado em" reflete só edições do lojista).
create or replace function public.touch_products_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if (new.click_count is distinct from old.click_count or new.last_click_at is distinct from old.last_click_at)
     and (row(new.title, new.description, new.price, new.compare_at_price, new.ml_url, new.category_id,
              new.models, new.material, new.includes, new.featured, new.active, new.sold_out, new.position, new.slug)
          is not distinct from
          row(old.title, old.description, old.price, old.compare_at_price, old.ml_url, old.category_id,
              old.models, old.material, old.includes, old.featured, old.active, old.sold_out, old.position, old.slug)) then
    return new;
  end if;
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists products_touch on public.products;
create trigger products_touch before update on public.products
  for each row execute function public.touch_products_updated_at();

-- ---------------------------------------------------------------------------
-- Row Level Security
